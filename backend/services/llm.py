import re
from dataclasses import dataclass
from typing import Literal
from dotenv import load_dotenv
from pathlib import Path
from os import getenv
import requests


ENV_FILEPATH = Path(__file__).parent / ".env"
load_dotenv(dotenv_path=ENV_FILEPATH)

ACCOUNT_ID = getenv("ACCOUNT_ID")
API_TOKEN = getenv("API_TOKEN")
MODEL = getenv("MODEL")

api_base_url = f"https://api.cloudflare.com/client/v4/accounts/{ACCOUNT_ID}/ai/run/"
headers = {"Authorization": f"Bearer {API_TOKEN}"}


def run_model(model: str, messages: list[dict]) -> str:
    """Запрос к cloudflare. Возвращает текстовый ответ"""
    payload = {"messages": messages}
    response = requests.post(f"{api_base_url}{model}", headers=headers, json=payload)
    response.raise_for_status()
    data = response.json()
    return data["result"]["choices"][0]["message"]["content"]


SkillRecommendationImpact = Literal["low"] | Literal["medium"] | Literal["high"] | Literal[""]


@dataclass(frozen=True)
class SkillRecommendation:
    title: str
    detail: str
    impact: SkillRecommendationImpact


def get_official_profession_of(profession: str) -> str:
    """Официальное название профессии из бытового"""
    prompt = f"""
    Ты — строгий классификатор профессий. Твоя единственная задача: преобразовать бытовое, жаргонное или неполное название профессии в официальное наименование согласно ОКПДТР или ЕКС.

    Правила, которые нельзя нарушать:
    1. На выходе — ТОЛЬКО официальное название профессии в именительном падеже.
    2. Запрещены: кавычки, пояснения, варианты («или»), пометки («возможно», «например»), точка в конце.
    3. Если бытовое название соответствует нескольким должностям — выбери одну, самую распространённую и универсальную.
    4. Если точного официального аналога нет — верни исходное название без изменений (но приведи его к нормальной форме).
    5. Не добавляй слова «Специалист», «Рабочий» и т.п., если их нет в официальном названии (но если есть — оставляй как есть).
    
    Примеры (строго следуй этому формату):
    Вход: айтишник → Выход: Специалист по информационным технологиям
    Вход: кадровик → Выход: Специалист по кадрам
    Вход: уборщица → Выход: Уборщик служебных помещений
    Вход: продавец в магазине одежды → Выход: Продавец непродовольственных товаров
    Вход: повар в детском саду → Выход: Повар
    Вход: архитектор баз данных → Выход: Архитектор баз данных
    Вход: джава-программист → Выход: Программист
    Вход: сисадмин → Выход: Системный администратор
    
    Сейчас выполни преобразование.
    
    Вход: {profession}
    Выход:
    """

    messages = [{"role": "user", "content": prompt}]
    try:
        return run_model(MODEL, messages)
    except Exception:
        return profession


def get_recommendations_by(*,
                           resume: str,
                           skills: list[str],
                           vacancies: list[str]
                           ) -> tuple[list[SkillRecommendation], str]:
    vacancy_params = "\n".join(f"вакансия {i}: {line}" for i, line in enumerate(vacancies, start=1))
    prompt = f"""
    Ты — эксперт по анализу рынка труда и подбору вакансий.

    Твоя задача: проанализировать разрыв между текущими навыками пользователя и требованиями из предложенных вакансий. На основе этого анализа ты должен вернуть ОДНИМ ВЫВОДОМ список из 3–7 наиболее ценных недостающих навыков, а также итоговое резюме с добавленными навыками.
    
    ВХОДНЫЕ ДАННЫЕ:
    - Резюме: {resume}
    - Мои навыки: {", ".join(skills)}
    - Вакансии (с требованиями, желательными навыками, зарплатами): {vacancy_params}
    
    ПРАВИЛА:
    1. Отбирай навыки ТОЛЬКО из требований или желательных навыков указанных вакансий.
    2. Новый навык НЕ должен присутствовать в поле «Мои навыки».
    3. Если количество новых навыков (которых нет у пользователя) больше 7 — выбери 7 самых ценных (по частоте, обязательности, влиянию на зарплату).
    4. Если новых навыков от 3 до 7 — выведи все.
    5. Если новых навыков меньше 3 — выведи все, которые есть. Если новых нет вообще — выбери от 3 до 7 самых частотных навыков из вакансий (даже если они уже есть у пользователя), но для каждого укажи impact: low и в detail объясни, что навык уже освоен, но важен для рынка.
    6. Для каждого навыка определи impact по шкале:
       - high: обязательный минимум в 2+ вакансиях или ключевой для всех трёх вакансий.
       - medium: желательный/плюс в 2+ вакансиях или обязательный в одной вакансии.
       - low: упоминается только в одной вакансии как желательный, либо встречается редко, либо (особый случай) навык уже есть у пользователя.
    7. В detail укажи конкретную причину (частоту, обязательность, связь с зарплатой) со ссылкой на «в анализируемых вакансиях» или «на trudvsem.ru».
    
    ФОРМАТ ВЫВОДА (строго один блок, без лишнего текста, без пояснений, без markdown-разметки, кроме переносов строк):
    
    Для каждого навыка выводи блок:
    title: <Добавьте|Освойте|Популярен такой навык, как> <Название навыка с заглавной буквы>
    detail: <одно предложение на русском>
    impact: high|medium|low
    
    После всех блоков (через пустую строку) выведи строку:
    Исправленное резюме: <Исходное резюме {resume}, но в конец списка «мои навыки» через запятую добавлены все рекомендованные навыки (без повторов, в том порядке, как они перечислены выше). Если навык уже был в исходных — не добавляй повторно, кроме случая, когда новых навыков нет (тогда добавь самый частотный один раз). Названия навыков — с заглавной буквы. После запятой — пробел. Не меняй остальную структуру резюме.>
    
    ПРИМЕР (для трёх навыков):
    
    title: Освойте навык: Docker
    detail: Указан как обязательное требование во всех трёх вакансиях и влияет на уровень зарплаты на trudvsem.ru.
    impact: high
    
    title: Добавьте навык: SQL
    detail: Встречается как желательный плюс в двух из трёх вакансий.
    impact: medium
    
    title: Популярен такой навык, как Redis
    detail: Упоминается только в одной вакансии как опциональный бонус.
    impact: low
    
    Исправленное резюме: Я Python-разработчик, мои навыки: FastAPI, Docker, SQL, Redis
    
    ВАЖНО:
    - Не выводи ничего, кроме указанного формата.
    - Не используй точки в конце строк (кроме точки внутри detail).
    - Не добавляй лишние переносы строк, кроме разделения между блоками навыков и перед «Исправленное резюме».
    - Количество навыков — всегда от 3 до 7, даже если пришлось взять уже имеющиеся.
    
    Теперь выполни задание для следующих входных данных:
    
    Резюме: {resume}
    Мои навыки: {", ".join(skills)}
    Вакансии: {vacancy_params}
    """

    messages = [{"role": "user", "content": prompt}]
    try:
        text = run_model(MODEL, messages)
    except Exception:
        return [], resume

    skills_pattern = r"title:\s*(.+?)\s*\n\s*detail:\s*(.+?)\s*\n\s*impact:\s*(high|medium|low)"
    skill_matches = re.findall(skills_pattern, text, re.IGNORECASE | re.DOTALL)

    new_resume_pattern = r"Исправленное резюме:\s*(.*?)(?:\n\s*(?:title|$)|$)"
    new_resume_match = re.search(new_resume_pattern, text, re.DOTALL)

    recommendations = [
        SkillRecommendation(title.strip(), detail.strip(), impact)
        for title, detail, impact in skill_matches
    ]

    new_resume = new_resume_match.group(1).strip() if new_resume_match else resume

    return recommendations, new_resume
